#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate _redirects: 301 from every legacy *.html URL to the clean URL."""
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SKIP_DIRS = {".git", "tools", "node_modules", ".workbuddy", "thumbs_svg"}
SKIP_FILES = {"404.html", "googlec618091bcb9edff2.html"}

rules = []
for dirpath, dirs, files in os.walk(ROOT):
    dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
    for f in files:
        if not f.endswith(".html") or f in SKIP_FILES:
            continue
        rel = os.path.relpath(os.path.join(dirpath, f), ROOT).replace(os.sep, "/")
        clean = rel[:-5]
        src = "/" + rel
        dst = "/" if clean == "index" else "/" + clean
        rules.append((src, dst))

rules = sorted(set(rules))
body = "\n".join("%s %s 301" % (a, b) for a, b in rules)
header = (
    "# Permanent redirects from the legacy *.html URLs to the clean URLs that\n"
    "# Cloudflare Workers Assets actually serves. Without this file the platform\n"
    "# answers 307 (temporary), which does not consolidate ranking signals as\n"
    "# reliably as a 301 does.\n"
    "# Generated by tools/gen_redirects.py on 2026-10-28.\n\n"
)
out = os.path.join(ROOT, "_redirects")
open(out, "w", encoding="utf-8", newline="\n").write(header + body + "\n")
print("wrote %d rules to %s" % (len(rules), out))
